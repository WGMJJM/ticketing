-- 所有 DATETIME(6) 存储 UTC；金额单位为人民币分。应用后的迁移不得修改。
CREATE TABLE user_account (
    id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT COMMENT '用户主键',
    username VARCHAR(64) NOT NULL COMMENT '唯一用户名，不区分大小写',
    password_hash VARCHAR(255) NOT NULL COMMENT '自适应密码哈希，禁止保存明文',
    status VARCHAR(16) NOT NULL DEFAULT 'ACTIVE' COMMENT 'ACTIVE 正常，DISABLED 停用',
    role VARCHAR(16) NOT NULL DEFAULT 'USER' COMMENT 'USER 用户，ADMIN 管理员',
    created_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6) COMMENT '创建时间 UTC',
    updated_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6) ON UPDATE CURRENT_TIMESTAMP(6) COMMENT '更新时间 UTC',
    PRIMARY KEY (id),
    UNIQUE KEY uk_user_username (username),
    CONSTRAINT ck_user_status CHECK (status IN ('ACTIVE', 'DISABLED')),
    CONSTRAINT ck_user_role CHECK (role IN ('USER', 'ADMIN'))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci COMMENT='用户账号';

CREATE TABLE activity (
    id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT COMMENT '活动主键',
    title VARCHAR(200) NOT NULL COMMENT '活动标题',
    category VARCHAR(24) NOT NULL COMMENT 'CONCERT 演唱会，FESTIVAL 音乐节，STAGE 舞台演出，EXHIBITION 展览，ESPORTS 电竞',
    city VARCHAR(64) NOT NULL COMMENT '城市',
    venue VARCHAR(200) NOT NULL COMMENT '场馆名称',
    description TEXT COMMENT '活动说明',
    status VARCHAR(16) NOT NULL DEFAULT 'DRAFT' COMMENT 'DRAFT 草稿，PUBLISHED 发布，CANCELLED 取消',
    created_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6) COMMENT '创建时间 UTC',
    updated_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6) ON UPDATE CURRENT_TIMESTAMP(6) COMMENT '更新时间 UTC',
    PRIMARY KEY (id),
    KEY idx_activity_discovery (status, city, category, id),
    CONSTRAINT ck_activity_category CHECK (category IN ('CONCERT', 'FESTIVAL', 'STAGE', 'EXHIBITION', 'ESPORTS')),
    CONSTRAINT ck_activity_status CHECK (status IN ('DRAFT', 'PUBLISHED', 'CANCELLED'))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci COMMENT='活动';

CREATE TABLE activity_session (
    id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT COMMENT '场次主键',
    activity_id BIGINT UNSIGNED NOT NULL COMMENT '所属活动',
    title VARCHAR(100) NOT NULL COMMENT '场次名称',
    starts_at DATETIME(6) NOT NULL COMMENT '开始时间 UTC',
    ends_at DATETIME(6) NOT NULL COMMENT '结束时间 UTC',
    status VARCHAR(16) NOT NULL DEFAULT 'SCHEDULED' COMMENT 'SCHEDULED 待开始，CANCELLED 取消，ENDED 结束',
    created_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6) COMMENT '创建时间 UTC',
    updated_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6) ON UPDATE CURRENT_TIMESTAMP(6) COMMENT '更新时间 UTC',
    PRIMARY KEY (id),
    KEY idx_session_activity_start (activity_id, starts_at, id),
    CONSTRAINT fk_session_activity FOREIGN KEY (activity_id) REFERENCES activity (id),
    CONSTRAINT ck_session_time CHECK (ends_at > starts_at),
    CONSTRAINT ck_session_status CHECK (status IN ('SCHEDULED', 'CANCELLED', 'ENDED'))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci COMMENT='活动场次';

CREATE TABLE ticket_sku (
    id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT COMMENT '票档主键',
    session_id BIGINT UNSIGNED NOT NULL COMMENT '所属场次',
    name VARCHAR(100) NOT NULL COMMENT '票档名称，不含座位号',
    price_cents BIGINT NOT NULL COMMENT '单价，人民币分',
    total_stock INT NOT NULL COMMENT '总库存',
    locked_stock INT NOT NULL DEFAULT 0 COMMENT '待支付订单预占库存',
    sold_stock INT NOT NULL DEFAULT 0 COMMENT '已支付库存',
    sale_starts_at DATETIME(6) NOT NULL COMMENT '开售时间 UTC',
    sale_ends_at DATETIME(6) NOT NULL COMMENT '停售时间 UTC',
    max_quantity_per_order INT NOT NULL DEFAULT 4 COMMENT '每单数量上限',
    status VARCHAR(16) NOT NULL DEFAULT 'DRAFT' COMMENT 'DRAFT 草稿，ON_SALE 上架，OFF_SALE 下架',
    created_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6) COMMENT '创建时间 UTC',
    updated_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6) ON UPDATE CURRENT_TIMESTAMP(6) COMMENT '更新时间 UTC',
    PRIMARY KEY (id),
    UNIQUE KEY uk_sku_session_name (session_id, name),
    UNIQUE KEY uk_sku_id_session (id, session_id),
    CONSTRAINT fk_sku_session FOREIGN KEY (session_id) REFERENCES activity_session (id),
    CONSTRAINT ck_sku_stock CHECK (total_stock >= 0 AND locked_stock >= 0 AND sold_stock >= 0 AND CAST(locked_stock AS SIGNED) + sold_stock <= total_stock),
    CONSTRAINT ck_sku_price CHECK (price_cents >= 0),
    CONSTRAINT ck_sku_sale_time CHECK (sale_ends_at > sale_starts_at),
    CONSTRAINT ck_sku_quantity CHECK (max_quantity_per_order > 0),
    CONSTRAINT ck_sku_status CHECK (status IN ('DRAFT', 'ON_SALE', 'OFF_SALE'))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci COMMENT='票档与权威库存';

CREATE TABLE ticket_order (
    id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT COMMENT '订单主键',
    order_no VARCHAR(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL COMMENT '唯一订单号',
    user_id BIGINT UNSIGNED NOT NULL COMMENT '下单用户',
    session_id BIGINT UNSIGNED NOT NULL COMMENT '订单所属唯一场次',
    status VARCHAR(16) NOT NULL DEFAULT 'PENDING' COMMENT 'PENDING 待支付，PAID 已支付，CANCELLED 取消，EXPIRED 超时',
    total_amount_cents BIGINT NOT NULL COMMENT '下单时应付金额快照，人民币分',
    idempotency_operation VARCHAR(32) CHARACTER SET ascii COLLATE ascii_bin NOT NULL COMMENT '业务操作域，如 CREATE_ORDER',
    idempotency_key VARCHAR(128) CHARACTER SET ascii COLLATE ascii_bin NOT NULL COMMENT '用户提交的幂等键',
    request_hash BINARY(32) NOT NULL COMMENT '规范化请求参数 SHA-256，检测同键异参',
    expires_at DATETIME(6) NOT NULL COMMENT '支付截止时间 UTC',
    paid_at DATETIME(6) NULL COMMENT '支付完成时间 UTC',
    created_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6) COMMENT '创建时间 UTC',
    updated_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6) ON UPDATE CURRENT_TIMESTAMP(6) COMMENT '更新时间 UTC',
    PRIMARY KEY (id),
    UNIQUE KEY uk_order_no (order_no),
    UNIQUE KEY uk_order_idempotency (user_id, idempotency_operation, idempotency_key),
    UNIQUE KEY uk_order_id_session (id, session_id),
    UNIQUE KEY uk_order_id_user (id, user_id),
    KEY idx_order_user_created (user_id, created_at, id),
    KEY idx_order_expiry (status, expires_at, id),
    KEY idx_order_session (session_id),
    CONSTRAINT fk_order_user FOREIGN KEY (user_id) REFERENCES user_account (id),
    CONSTRAINT fk_order_session FOREIGN KEY (session_id) REFERENCES activity_session (id),
    CONSTRAINT ck_order_amount CHECK (total_amount_cents >= 0),
    CONSTRAINT ck_order_expiry CHECK (expires_at > created_at),
    CONSTRAINT ck_order_paid_time CHECK ((status = 'PAID' AND paid_at IS NOT NULL) OR (status <> 'PAID' AND paid_at IS NULL)),
    CONSTRAINT ck_order_status CHECK (status IN ('PENDING', 'PAID', 'CANCELLED', 'EXPIRED'))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci COMMENT='票务订单及幂等记录';

CREATE TABLE ticket_order_item (
    id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT COMMENT '订单明细主键',
    order_id BIGINT UNSIGNED NOT NULL COMMENT '所属订单',
    sku_id BIGINT UNSIGNED NOT NULL COMMENT '购买票档',
    session_id BIGINT UNSIGNED NOT NULL COMMENT '场次，用复合外键约束票档和订单一致',
    quantity INT NOT NULL COMMENT '购买数量',
    unit_price_cents BIGINT NOT NULL COMMENT '下单单价快照，人民币分',
    sku_name_snapshot VARCHAR(100) NOT NULL COMMENT '下单票档名称快照',
    created_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6) COMMENT '创建时间 UTC',
    PRIMARY KEY (id),
    UNIQUE KEY uk_item_order (order_id),
    UNIQUE KEY uk_item_ticket_reference (id, order_id, sku_id),
    KEY idx_item_order_session (order_id, session_id),
    KEY idx_item_sku_session (sku_id, session_id),
    CONSTRAINT fk_item_order_session FOREIGN KEY (order_id, session_id) REFERENCES ticket_order (id, session_id),
    CONSTRAINT fk_item_sku_session FOREIGN KEY (sku_id, session_id) REFERENCES ticket_sku (id, session_id),
    CONSTRAINT ck_item_quantity CHECK (quantity > 0),
    CONSTRAINT ck_item_price CHECK (unit_price_cents >= 0)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci COMMENT='订单票档明细，第一版每单仅一个票档';

CREATE TABLE payment_record (
    id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT COMMENT '支付流水主键',
    payment_no VARCHAR(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL COMMENT '唯一模拟支付流水号',
    order_id BIGINT UNSIGNED NOT NULL COMMENT '关联订单',
    amount_cents BIGINT NOT NULL COMMENT '支付金额快照，人民币分',
    status VARCHAR(16) NOT NULL DEFAULT 'PENDING' COMMENT 'PENDING 待处理，SUCCEEDED 成功，FAILED 失败，CLOSED 关闭',
    paid_at DATETIME(6) NULL COMMENT '支付成功时间 UTC',
    created_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6) COMMENT '创建时间 UTC',
    updated_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6) ON UPDATE CURRENT_TIMESTAMP(6) COMMENT '更新时间 UTC',
    PRIMARY KEY (id),
    UNIQUE KEY uk_payment_no (payment_no),
    UNIQUE KEY uk_payment_order (order_id),
    CONSTRAINT fk_payment_order FOREIGN KEY (order_id) REFERENCES ticket_order (id),
    CONSTRAINT ck_payment_amount CHECK (amount_cents >= 0),
    CONSTRAINT ck_payment_time CHECK ((status = 'SUCCEEDED' AND paid_at IS NOT NULL) OR (status <> 'SUCCEEDED' AND paid_at IS NULL)),
    CONSTRAINT ck_payment_status CHECK (status IN ('PENDING', 'SUCCEEDED', 'FAILED', 'CLOSED'))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci COMMENT='模拟支付流水，第一版每订单一条可重试流水';

CREATE TABLE waitlist_entry (
    id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT COMMENT '候补主键，同票档内部 FIFO 排队顺序',
    user_id BIGINT UNSIGNED NOT NULL COMMENT '候补用户',
    sku_id BIGINT UNSIGNED NOT NULL COMMENT '候补票档',
    quantity INT NOT NULL COMMENT '候补数量',
    status VARCHAR(16) NOT NULL DEFAULT 'WAITING' COMMENT 'WAITING 等待，ALLOCATED 分配，COMPLETED 完成，CANCELLED 取消，EXPIRED 过期',
    reserved_order_id BIGINT UNSIGNED NULL COMMENT '分配后预留的订单',
    active_marker TINYINT GENERATED ALWAYS AS (CASE WHEN status IN ('WAITING', 'ALLOCATED') THEN 1 ELSE NULL END) STORED COMMENT '活动候补标记，用于唯一性约束',
    expires_at DATETIME(6) NOT NULL COMMENT '候补截止时间 UTC',
    created_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6) COMMENT '创建时间 UTC',
    updated_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6) ON UPDATE CURRENT_TIMESTAMP(6) COMMENT '更新时间 UTC',
    PRIMARY KEY (id),
    UNIQUE KEY uk_waitlist_active (user_id, sku_id, active_marker),
    UNIQUE KEY uk_waitlist_order (reserved_order_id),
    KEY idx_waitlist_queue (sku_id, status, id),
    KEY idx_waitlist_user (user_id, created_at, id),
    KEY idx_waitlist_expiry (status, expires_at, id),
    KEY idx_waitlist_order_user (reserved_order_id, user_id),
    CONSTRAINT fk_waitlist_user FOREIGN KEY (user_id) REFERENCES user_account (id),
    CONSTRAINT fk_waitlist_sku FOREIGN KEY (sku_id) REFERENCES ticket_sku (id),
    CONSTRAINT fk_waitlist_order_user FOREIGN KEY (reserved_order_id, user_id) REFERENCES ticket_order (id, user_id),
    CONSTRAINT ck_waitlist_quantity CHECK (quantity > 0),
    CONSTRAINT ck_waitlist_expiry CHECK (expires_at > created_at),
    CONSTRAINT ck_waitlist_allocation CHECK (status NOT IN ('ALLOCATED', 'COMPLETED') OR reserved_order_id IS NOT NULL),
    CONSTRAINT ck_waitlist_status CHECK (status IN ('WAITING', 'ALLOCATED', 'COMPLETED', 'CANCELLED', 'EXPIRED'))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci COMMENT='票档候补队列';

CREATE TABLE electronic_ticket (
    id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT COMMENT '电子票主键',
    ticket_no VARCHAR(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL COMMENT '唯一电子票编号',
    order_id BIGINT UNSIGNED NOT NULL COMMENT '来源订单',
    order_item_id BIGINT UNSIGNED NOT NULL COMMENT '来源订单明细',
    sku_id BIGINT UNSIGNED NOT NULL COMMENT '票档',
    owner_id BIGINT UNSIGNED NOT NULL COMMENT '持票用户，与订单用户一致',
    sequence_no INT NOT NULL COMMENT '明细内第几张票，从 1 开始',
    credential_digest BINARY(32) NOT NULL COMMENT '完整票券凭证的 SHA-256 摘要，不保存明文凭证',
    credential_key_version SMALLINT NOT NULL COMMENT '服务端凭证签名密钥版本',
    status VARCHAR(16) NOT NULL DEFAULT 'UNUSED' COMMENT 'UNUSED 未用，USED 已用，VOID 作废',
    used_at DATETIME(6) NULL COMMENT '核销时间 UTC',
    checked_by BIGINT UNSIGNED NULL COMMENT '核销工作人员',
    created_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6) COMMENT '创建时间 UTC',
    updated_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6) ON UPDATE CURRENT_TIMESTAMP(6) COMMENT '更新时间 UTC',
    PRIMARY KEY (id),
    UNIQUE KEY uk_ticket_no (ticket_no),
    UNIQUE KEY uk_ticket_digest (credential_digest),
    UNIQUE KEY uk_ticket_item_sequence (order_item_id, sequence_no),
    KEY idx_ticket_owner (owner_id, created_at, id),
    KEY idx_ticket_order_owner (order_id, owner_id),
    KEY idx_ticket_item_reference (order_item_id, order_id, sku_id),
    KEY idx_ticket_sku (sku_id),
    KEY idx_ticket_checker (checked_by),
    CONSTRAINT fk_ticket_order_owner FOREIGN KEY (order_id, owner_id) REFERENCES ticket_order (id, user_id),
    CONSTRAINT fk_ticket_item FOREIGN KEY (order_item_id, order_id, sku_id) REFERENCES ticket_order_item (id, order_id, sku_id),
    CONSTRAINT fk_ticket_sku FOREIGN KEY (sku_id) REFERENCES ticket_sku (id),
    CONSTRAINT fk_ticket_checker FOREIGN KEY (checked_by) REFERENCES user_account (id),
    CONSTRAINT ck_ticket_sequence CHECK (sequence_no > 0),
    CONSTRAINT ck_ticket_key_version CHECK (credential_key_version > 0),
    CONSTRAINT ck_ticket_used_time CHECK ((status = 'USED' AND used_at IS NOT NULL AND checked_by IS NOT NULL) OR (status <> 'USED' AND used_at IS NULL AND checked_by IS NULL)),
    CONSTRAINT ck_ticket_status CHECK (status IN ('UNUSED', 'USED', 'VOID'))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci COMMENT='电子票及核销状态';

CREATE TABLE outbox_event (
    id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT COMMENT '本地事件主键',
    event_id VARCHAR(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL COMMENT '全局唯一事件 ID',
    aggregate_type VARCHAR(64) NOT NULL COMMENT '聚合类型，如 ORDER',
    aggregate_id BIGINT UNSIGNED NOT NULL COMMENT '聚合对象主键',
    event_type VARCHAR(100) NOT NULL COMMENT '事件类型',
    payload JSON NOT NULL COMMENT '事件数据，金额为分，ID 为字符串，日期为带时区 ISO 8601',
    status VARCHAR(16) NOT NULL DEFAULT 'PENDING' COMMENT 'PENDING 待投递，PROCESSING 投递中，SENT 已确认，FAILED 待人工处理',
    retry_count INT NOT NULL DEFAULT 0 COMMENT '已重试次数',
    next_retry_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6) COMMENT '下一次尝试时间或处理租约截止时间 UTC',
    last_error VARCHAR(1000) NULL COMMENT '脱敏后的投递错误摘要',
    sent_at DATETIME(6) NULL COMMENT '代理确认接收时间 UTC',
    created_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6) COMMENT '创建时间 UTC',
    updated_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6) ON UPDATE CURRENT_TIMESTAMP(6) COMMENT '更新时间 UTC',
    PRIMARY KEY (id),
    UNIQUE KEY uk_outbox_event_id (event_id),
    KEY idx_outbox_dispatch (status, next_retry_at, id),
    KEY idx_outbox_aggregate (aggregate_type, aggregate_id, id),
    CONSTRAINT ck_outbox_retry CHECK (retry_count >= 0),
    CONSTRAINT ck_outbox_sent_time CHECK ((status = 'SENT' AND sent_at IS NOT NULL) OR (status <> 'SENT' AND sent_at IS NULL)),
    CONSTRAINT ck_outbox_status CHECK (status IN ('PENDING', 'PROCESSING', 'SENT', 'FAILED'))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci COMMENT='事务可靠事件发件箱';
